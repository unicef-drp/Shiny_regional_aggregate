GetIncompleteVRObservationsAndYears <- function(
  mcmc.meta ##<< ##<< \code{mcmc.meta} from \code{\link{RunMCMC}}.
) {
  incompletevrobsandyears.Lc.i2 <- list()
  for (c in 1:mcmc.meta$data$C) {
    if (is.null(mcmc.meta$data$isincompletevr.Lc.j[[c]])) {
      incompletevrobsandyears.Lc.i2[[c]] <- matrix(NA, 1, 2)
    } else {
      incompletevrobsandyears.Lc.i2[[c]] <- cbind(mcmc.meta$data$uvr.Lc.j[[c]][
        mcmc.meta$data$isincompletevr.Lc.j[[c]] == 1], 
        mcmc.meta$data$yearvr.Lc.j[[c]][
          mcmc.meta$data$isincompletevr.Lc.j[[c]] == 1])
    }
  }
  ##value<< List of matrices with 2 columns each, with the first column listing incomplete VR 
  ## observations and the second listing the observation years.
  return(incompletevrobsandyears.Lc.i2)
}
