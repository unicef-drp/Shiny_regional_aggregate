GetLastObservationYearInValidationTrainingSet <- function(# Get last observation year in training set 
  ### for validation exercise.
  mcmc.meta ##<< \code{mcmc.meta} from \code{\link{RunMCMC}}.
) {
  Ytr.c <- rep(NA, mcmc.meta$data$C)
  for(c in 1:mcmc.meta$data$C) {
    Ytr.c[c] <- max(mcmc.meta$jags.data$year.ci[c, mcmc.meta$data.val$geti.training.cj[
      c, !is.na(mcmc.meta$data.val$geti.training.cj[c, ])]])
  }
  ##value<< Vector of last observation year in training set for validation exercise.
  return(Ytr.c)
}
